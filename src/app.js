const express = require('express');
const helmet = require('helmet');
const cors = require('cors');
const compression = require('compression');
const morgan = require('morgan');
const rateLimit = require('express-rate-limit');
const { log, stream } = require('./utils/logger');
const { notFound, errorHandler } = require('./middleware/errors');

const app = express();
app.set('trust proxy', 1);
app.use(helmet());
app.use(cors());
app.use(compression());
app.use(express.json({ limit: '20kb' }));
app.use(morgan('combined', { stream }));
app.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/health', (req, res) => res.status(200).json({ status: 'ok', service: 'comp3123-assignment1-api', database: require('mongoose').connection.readyState === 1 ? 'connected' : 'disconnected', timestamp: new Date().toISOString() }));
app.use('/api/v1/user', require('./routes/user'));
app.use('/api/v1/emp', require('./routes/employee'));
app.use(notFound);
app.use(errorHandler);
app.on('ready', () => log('info', 'Application ready'));
module.exports = app;
